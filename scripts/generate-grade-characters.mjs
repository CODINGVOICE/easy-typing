import { mkdir, readFile, writeFile } from "node:fs/promises";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const inputPath = resolve(__dirname, "../grade.md");
const outputPath = resolve(__dirname, "../src/gradeCharacters.ts");

const gradeNumbers = new Map([
  ["一", 1],
  ["二", 2],
  ["三", 3],
  ["四", 4],
  ["五", 5],
  ["六", 6],
  ["七", 7],
  ["八", 8],
  ["九", 9]
]);

const gradeTitles = new Map([
  [1, "一年级"],
  [2, "二年级"],
  [3, "三年级"],
  [4, "四年级"],
  [5, "五年级"],
  [6, "六年级"],
  [7, "七年级"],
  [8, "八年级"],
  [9, "九年级"]
]);

const simpleGradeLevels = [1, 2, 3, 4, 5];
const gradeLinePattern = /^([^（:：]+?)汉字(?:（[^）]*）)?[：:](.*)$/u;
const hanCharacterPattern = /[\u3400-\u9fff\uf900-\ufaff]/gu;

const gradeBuckets = new Map(
  Array.from(gradeNumbers.values(), (grade) => [
    grade,
    {
      chars: [],
      seen: new Set()
    }
  ])
);

const content = await readFile(inputPath, "utf8");
const lines = content.split(/\r?\n/).map((line) => line.trim()).filter(Boolean);

for (const line of lines) {
  const lineMatch = line.match(gradeLinePattern);

  if (!lineMatch) {
    continue;
  }

  const [, label, body] = lineMatch;
  const gradeMatch = label.match(/^([一二三四五六七八九])年级/u);

  if (!gradeMatch) {
    continue;
  }

  const grade = gradeNumbers.get(gradeMatch[1]);
  const bucket = grade ? gradeBuckets.get(grade) : undefined;

  if (!bucket) {
    continue;
  }

  for (const char of body.match(hanCharacterPattern) ?? []) {
    if (bucket.seen.has(char)) {
      continue;
    }

    bucket.seen.add(char);
    bucket.chars.push(char);
  }
}

const missingSimpleGrades = simpleGradeLevels.filter(
  (grade) => !gradeBuckets.get(grade)?.chars.length
);

if (missingSimpleGrades.length) {
  throw new Error(
    `Missing grade data for ${missingSimpleGrades
      .map((grade) => gradeTitles.get(grade))
      .join(", ")} in grade.md`
  );
}

const groups = Array.from(gradeBuckets.entries())
  .filter(([, bucket]) => bucket.chars.length > 0)
  .map(([grade, bucket]) => ({
    grade,
    title: gradeTitles.get(grade),
    chars: bucket.chars.join("")
  }));

const gradeUnion = groups.map((group) => group.grade).join(" | ");
const groupLines = groups
  .map(
    (group) => `  {
    grade: ${group.grade},
    title: ${JSON.stringify(group.title)},
    chars: ${JSON.stringify(group.chars)}
  }`
  )
  .join(",\n");

const file = `// Generated by scripts/generate-grade-characters.mjs from grade.md. Do not edit by hand.
export type GradeLevel = ${gradeUnion};

export interface GradeCharacterGroup {
  grade: GradeLevel;
  title: string;
  chars: string;
}

export const SIMPLE_GRADE_LEVELS = [1, 2, 3, 4, 5] as const;
export type SimpleGradeLevel = (typeof SIMPLE_GRADE_LEVELS)[number];

export const GRADE_CHARACTER_GROUPS: readonly GradeCharacterGroup[] = [
${groupLines}
];
`;

await mkdir(dirname(outputPath), { recursive: true });
await writeFile(outputPath, file, "utf8");

const summary = groups
  .map((group) => `${group.title}: ${Array.from(group.chars).length}`)
  .join(", ");

console.log(`Generated grade characters from grade.md. ${summary}`);
